/* возвращает индекс варианта или null */
window.probeMatch=function(qid,text){
  var t=(text||'').toLowerCase().replace(/ё/g,'е').trim();
  if(!t||t.length>90)return null;
  var syn=PROBE_SYN[qid];if(!syn)return null;
  /* отрицание сильнее общего совпадения: «лягу, но НЕ усну» — это не «отосплюсь» */
  if(qid==='load'&&/(не усну|не могу уснуть|не засып|не сплю|бессонн|верчусь|ворочаюсь)/.test(t))return 2;
  if(qid==='sugar'&&/(не тянет|не хочет|не тянуло|почти не)/.test(t))return 0;
  if(qid==='dip'&&/(не вырубает|не сплю|не тянет)/.test(t))return 0;
  /* «всегда» — это про постоянство, а не про время: берём самый тяжёлый вариант */
  if(ALWAYS.test(t)&&!/не /.test(t)){
    var q=null;for(var k=0;k<PROBE.length;k++)if(PROBE[k].id===qid)q=PROBE[k];
    if(q){var wi=0;for(var j=1;j<q.opts.length;j++)if(q.opts[j].v>q.opts[wi].v)wi=j;return wi;}}
  var best=null;
  for(var i=0;i<syn.length;i++){
    var m=t.match(new RegExp(syn[i].source,'g'));
    if(m&&(!best||m.length>best.n))best={i:i,n:m.length};}
  return best?best.i:null;};

/* считает утечки; возвращает {index, top, parts, answers} */
function probeResult(ans){
  var sum={light:0,night:0,sugar:0},cnt={light:0,night:0,sugar:0};
  PROBE.forEach(function(q){
    var a=ans[q.id];if(a==null)return;
    var o=q.opts[a];sum[q.leak]+=o.v;cnt[q.leak]++;});
  var parts=[];
  Object.keys(sum).forEach(function(k){
    if(!cnt[k])return;
    parts.push({id:k,v:Math.round(sum[k]/cnt[k]),name:LEAKS[k].name});});
  parts.sort(function(a,b){return b.v-a.v;});
  var all=parts.reduce(function(s,p){return s+p.v;},0)/(parts.length||1);
  var top=parts[0];
  /* если и худший блок в порядке — честно говорим, что дыры нет */
  if(!top||top.v<35)top={id:'none',v:top?top.v:0,name:LEAKS.none.name};
  return {index:Math.max(0,Math.min(100,Math.round(100-all))),top:top,parts:parts};}

/* доля заряда, уходящая в главную утечку — для фразы «отсюда уходит четверть» */
function leakShare(res){
  if(!res.top||res.top.id==='none')return 0;
  var t=res.parts.reduce(function(s,p){return s+p.v;},0);
  if(!t)return 25;
  /* доля от всех потерь, а не от суммы блоков: при нескольких дырах цифра не занижается */
  return Math.max(20,Math.min(60,Math.round(res.top.v/t*100)));}

/* «где ты среди других»: берём худший ответ ВНУТРИ найденной утечки — тогда
   фраза стоит рядом со своей темой, а не про случайный вопрос.
   Плюс отдельной строкой хвалим самый сильный ответ, если он есть. */
function rankLine(ans,leakId){
  var worst=null,best=null;
  PROBE.forEach(function(q){
    var a=ans[q.id];if(a==null)return;
    var o=q.opts[a];
    if((!leakId||leakId==='none'||q.leak===leakId)&&(!worst||o.v>worst.o.v))worst={q:q,o:o};
    if(o.v<=20&&(!best||o.v<best.o.v))best={q:q,o:o};});
  var out=[];
  if(worst&&worst.o.v>=50)
    out.push('И ты не один: так же отвечают '+worst.o.pct+'% — этот пункт сейчас и съедает больше всего.');
  if(best)
    out.push('А вот тут ты в меньшинстве в хорошем смысле: «'+best.o.t+'» выбирают только '+best.o.pct+'%.');
  return out.length?out.join('\n'):null;}

/* сверка самооценки с расчётом */
function mirrorLine(said,calc){
  var d=said-calc;
  if(d>=8)return 'Ты сказал '+said+', я насчитал '+calc+'. Ты себя переоцениваешь на '+d+
    ' — так делают почти все, у кого утро идёт без света: усталость есть, а причину видно только к вечеру.';
  if(d<=-8)return 'Ты сказал '+said+', я насчитал '+calc+'. Ты к себе строже, чем данные: запас есть, просто он не чувствуется.';
  return 'Ты сказал '+said+', я насчитал '+calc+'. Совпало почти в точку — себя ты слышишь хорошо.';}
